def normalize_category(sku_name: str) -> str:
    """根据 SKU 名称前缀匹配标准化 category, 找不到返回 '其他'。"""
    if not sku_name:
        return "其他"
    for prefix, cat in SKU_PREFIX_TO_CATEGORY:
        if prefix in sku_name:
            return cat
    return "其他"


def keywords_for_category(category: str) -> list[str]:
    """返回该 category 关联到 alert 时的命中关键词。"""
    return CATEGORY_KEYWORDS.get(category, [])
